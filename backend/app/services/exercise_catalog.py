def _ex(eid, places, level, tags, muscles, equipment, met, dosage, en, ru):
    """dosage: ("time", sets, seconds, rest) or ("reps", sets, reps, rest)."""
    mode, sets, amount, rest = dosage
    return {
        "id": eid,
        "places": places,
        "level": level,
        "tags": tags,
        "muscles": muscles,
        "equipment": equipment,
        "met": met,
        "dosage": {
            "mode": mode,
            "sets": sets,
            "reps": amount if mode == "reps" else None,
            "seconds": amount if mode == "time" else None,
            "rest_sec": rest,
        },
        "text": {"en": en, "ru": ru},
    }


def _t(name, description, steps, mistakes):
    return {"name": name, "description": description, "steps": steps, "mistakes": mistakes}


