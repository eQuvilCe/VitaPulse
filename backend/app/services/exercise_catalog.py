def kcal_per_min(met: float, weight_kg: float) -> float:
    return round(met * 3.5 * weight_kg / 200, 1)


def localize_exercise(ex: dict, lang: str, weight_kg: float) -> dict:
    text = ex["text"]["ru" if lang == "ru" else "en"]
    return {
        "id": ex["id"],
        **text,
        "muscles": ex["muscles"],
        "level": ex["level"],
        "places": ex["places"],
        "equipment": ex["equipment"],
        "tags": ex["tags"],
        "met": ex["met"],
        "kcal_per_min": kcal_per_min(ex["met"], weight_kg),
        "dosage": ex["dosage"],
        "image_url": None,
    }


SECONDS_PER_REP = 3
# Active rest between sets (walking about, catching breath).
REST_MET = 3.0


def _item_seconds(item: dict) -> int:
    if item["mode"] == "time":
        return item["seconds"]
    count = int(str(item["reps"]).split("-")[-1].split()[0])
    if "each" in str(item["reps"]):
        count *= 2
    return count * SECONDS_PER_REP


def localize_workout(w: dict, lang: str, weight_kg: float) -> dict:
    key = "ru" if lang == "ru" else "en"
    items, equipment, kcal = [], [], 0.0
    for ex_id, override in w["items"]:
        ex = BY_ID[ex_id]
        d = ex["dosage"]
        # Without an override the item runs once per round (or the catalog sets if one round).
        mode, sets, amount, rest = override or (
            d["mode"],
            d["sets"] if w["rounds"] == 1 else 1,
            d["seconds"] if d["mode"] == "time" else d["reps"],
            d["rest_sec"],
        )
        item = {
            "exercise_id": ex_id,
            "name": ex["text"][key]["name"],
            "mode": mode,
            "sets": sets,
            "seconds": amount if mode == "time" else None,
            "reps": amount if mode == "reps" else None,
            "rest_sec": rest,
        }
        items.append(item)
        repeats = sets * w["rounds"]
        kcal += _item_seconds(item) * repeats / 60 * kcal_per_min(ex["met"], weight_kg)
        kcal += rest * repeats / 60 * kcal_per_min(REST_MET, weight_kg)
        # The first listed equipment is the main one; the rest are alternatives.
        if ex["equipment"][0] not in equipment:
            equipment.append(ex["equipment"][0])
    title, description = w["text"][key]
    return {
        "id": w["id"],
        "title": title,
        "description": description,
        "level": w["level"],
        "place": w["place"],
        "tags": w["tags"],
        "equipment": [e for e in equipment if e != "none"] or ["none"],
        "duration_min": w["duration_min"],
        "kcal_estimate": round(kcal),
        "rounds": w["rounds"],
        "items": items,
    }
